"""Scoreboard of the proxy-market research, written from the result files (every number comes from
b3/proxy_research.py; nothing is typed by hand).

    python -m b3.proxy_report            -> research/proxies/SCOREBOARD.md and scoreboard.json
"""

from __future__ import annotations

import json
from pathlib import Path

from b3.markets import MARKETS
from b3.proxy_research import OUT_DIR, ledger_rows
from b3.strategies.proxies import RULES

SPLITS = ("exploration", "validation", "final_test")


def collect(out_dir: Path | None = None) -> list[dict]:
    """One row per (rule, market) with the latest result of each split that was read."""
    out_dir = out_dir or OUT_DIR
    latest: dict[tuple, dict] = {}
    for f in sorted((out_dir / "results").glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        latest[(d["rule"], d["symbol"], d["split"])] = d
    rows = []
    for rule in RULES:
        for sym in MARKETS:
            row = {"rule": rule, "name": RULES[rule].name, "timeframe_min": RULES[rule].timeframe_min,
                   "symbol": sym, "stands_for": MARKETS[sym].stands_for}
            for split in SPLITS:
                d = latest.get((rule, sym, split))
                if d is None:
                    continue
                b, c = d["scenarios"]["base"], d["scenarios"]["conservative"]
                row[split] = {
                    "decision": d["gates"]["decision"], "fails": d["gates"]["fails"],
                    "start": d["start_utc"][:10], "end": d["end_utc"][:10],
                    "trades": b["trades"], "trades_per_year": round(b["trades_per_year"], 1),
                    "mean_gross_pct": round(b.get("mean_gross_pct", 0.0), 4),
                    "net_base_pct": round(b["net_return_pct"], 2), "net_conservative_pct": round(c["net_return_pct"], 2),
                    "max_drawdown_base_pct": round(b.get("max_drawdown_pct", 0.0), 1),
                    "cost_round_trip_base_pct": d["cost_round_trip_base_pct"],
                    "per_year_base_pct": b.get("per_year_return_pct", {}),
                }
            if any(s in row for s in SPLITS):
                rows.append(row)
    return rows


def _cell(r: dict | None) -> str:
    if r is None:
        return "-"
    return f"{r['decision']} ({r['net_base_pct']:+.1f}% / {r['net_conservative_pct']:+.1f}%)"


def markdown(rows: list[dict], reads: int) -> str:
    lines = ["# Proxy markets scoreboard", "",
             "Generated by `python -m b3.proxy_report` from research/proxies/results. Cells: decision "
             "(net at base cost / net at conservative cost, compounded over the split, 1 unit per trade, no leverage).",
             f"Reads in the ledger: {reads}. Validation and final test are read once per rule and market.", "",
             "| Rule | TF | Market | Trades/yr | Gross/trade | Exploration | Validation | Final test |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        e = r.get("exploration")
        lines.append(f"| {r['rule']} {r['name'].split('_', 1)[1]} | {r['timeframe_min']}m | {r['symbol']} | "
                     f"{e['trades_per_year'] if e else '-'} | {(str(e['mean_gross_pct']) + '%') if e else '-'} | "
                     f"{_cell(e)} | {_cell(r.get('validation'))} | {_cell(r.get('final_test'))} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    rows = collect()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "scoreboard.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    (OUT_DIR / "SCOREBOARD.md").write_text(markdown(rows, len(ledger_rows())), encoding="utf-8")
    passed = [(r["rule"], r["symbol"]) for r in rows if r.get("exploration", {}).get("decision") == "passed"]
    print(f"{len(rows)} rule x market rows; passed exploration: {passed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
