"""Broker interface. The engine only talks to this Protocol.

Contract notes for adapters:
- `bars` may include the still-forming candle; the ENGINE discards it.
- `send` must be idempotent per `client_id` (a resend returns the same result).
- Fills of orders sent through `send` are returned in the OrderResult only.
  Server-originated fills (stop-outs, close_all) are delivered by
  `drain_fills`, each exactly once.
- `find_fill` lets the engine recover after a timeout on `send`.
"""

from __future__ import annotations

from typing import Protocol

from live.core.models import (
    AccountState, Bar, Fill, OrderRequest, OrderResult, Position, SymbolSpec,
)


class Broker(Protocol):
    def bars(self, symbol: str, timeframe_min: int, count: int) -> list[Bar]: ...
    def symbol_spec(self, symbol: str) -> SymbolSpec: ...
    def positions(self) -> list[Position]: ...
    def account(self) -> AccountState: ...
    def last_price(self, symbol: str) -> float: ...
    def send(self, req: OrderRequest) -> OrderResult: ...
    def find_fill(self, client_id: str) -> Fill | None: ...
    def cancel_all(self) -> None: ...
    def close_all(self, reason: str = "") -> None: ...
    def drain_fills(self) -> list[Fill]: ...
